st.markdown("### 🛡️ 工程可靠性 (生产级保障)")
st.markdown("""
评测系统要真正可用,不能只在理想情况下跑通。我们做了一套生产级保障:

| 能力 | 实现 | 解决什么 |
|---|---|---|
| **自动重试** | LLM 调用失败自动重试 3 次(指数退避) | API 抖动不再让单条约束变 error,不污染评分 |
| **可复现** | 固定 seed + temperature=0 + 记录模型版本 | 同一对话今天评和明天评结果一致,经得起复现验证 |
| **结果缓存** | (对话+约束+模型) 哈希缓存 | 重复评测秒出、省 API 费用 |
| **并发评测** | 多约束并发判定(线程池) | 单通对话评测从 ~30 秒降到 ~5 秒 |
| **自一致性投票** | 关键约束判 3 次取多数票 | 抹平单次 LLM 判定的偶发抖动,提升可靠性 |
| **鲁棒解析** | 容错 markdown 围栏/转义/截断的 JSON 解析 | LLM 输出格式异常不再导致评测失败 |
| **语义容错** | 流程识别支持同义词(告知≈通知≈跟您说) | 减少"模型说了但用词不同"的误判 |
| **空对话保护** | 区分"无法评测"与"真实低分" | 对话生成失败时明确提示,不给误导性 0 分 |

**设计原则**: 把所有 LLM 调用收敛到统一客户端层,重试/缓存/seed 集中治理,而非散落各处。
""")

